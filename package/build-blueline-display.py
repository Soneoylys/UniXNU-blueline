#!/usr/bin/env python3
"""Build GopFramebuffer's NativeLegacyDisplay for iPadOS 18.7.11 (22H384) as build/native-legacy-display/
libNativeLegacyDisplay.late.a, the archive XNU_NATIVE_LEGACY_DISPLAY links. The blueline counterpart of UniXNU-sheng's
scripts/build-gop-legacy-display.py (21H461), with the ABI of docs/DISPLAY-22H384.md:
  - IOMobileFramebufferLegacy: 368 vtable slots, instance 0x19c0, fields width/height 6088/6092, current swap 5736, queue
    head/tail 5744/5752, vsync clients 5856, request surfaces 2632, request links 3072/3080, state setter slot 364;
  - owned slots 296 startHardware, 298 kickSwapQueue, 304 validateSwap, 309 getRefreshAttributes (21H461 288/290/296/301),
    abstract leaves 212 214 247 248 314 315 347 348 355;
  - the display's CPU copy fallback is removed: a frame the GPU hand-off refuses stays pending (owner: no CPU rendering);
  - original bindings at prelinked addresses (kernelcache - 0x1000000), each checked against the 22H384 kernelcache and
    the built kernel before use.
The board hooks are package/BluelineDisplayProbe.cpp; the GPU hand-off presenter is GopFramebuffer's NativeGOPPresenter."""
from pathlib import Path
import argparse, hashlib, json, re, struct, subprocess, sys

p = argparse.ArgumentParser(description=__doc__)
p.add_argument('--tree', type=Path, required=True)
p.add_argument('--components', type=Path, required=True)
p.add_argument('--kernel', type=Path, required=True, help='a built kernel of this profile (bindings are checked in it)')
p.add_argument('--kernelcache', type=Path, required=True, help='the decompressed 22H384 kernelcache')
a = p.parse_args()
tree, components = a.tree.resolve(), a.components.resolve()
sys.path.insert(0, str(components / 'kits/XnuPrelink'))
from native_prelink import macho, backed_offset, exports  # noqa: E402

here = Path(__file__).resolve().parent
gop = components / 'drivers/GopFramebuffer'
out = tree / 'build/native-legacy-display'
out.mkdir(parents=True, exist_ok=True)
SHIFT = 0x1000000
SLOTS, SIZE = 368, 0x19c0
PURE = [212, 214, 247, 248, 314, 315, 347, 348, 355]
OWNED_BASE = [0, 1, 7, 14, 84, 86, 87, 141, 155, 184, 188, 296, 298, 304, 309]


def fail(why):
    raise SystemExit('build-blueline-display: ' + why)


class Image:
    def __init__(self, path):
        self.raw = path.read_bytes()
        self.im = macho(self.raw)

    def read(self, va, n):
        at = backed_offset(self.im['segments'], va, n, len(self.raw))
        return self.raw[at:at + n]


kc, ours = Image(a.kernelcache), Image(a.kernel)

# 1. Header for the exact original class.
header = '''// SPDX-License-Identifier: BSD-2-Clause-Patent
// Generated by UniXNU-blueline package/build-blueline-display.py for 22H384: opaque storage and dispatch layout of the
// original IOMobileFramebufferLegacy (docs/DISPLAY-22H384.md). Only qualified base prototypes may be called from source.
#pragma once
#include <IOKit/IOService.h>
#include <libkern/libkern.h>
struct OriginalLegacySwapRequest;
class IOMobileFramebufferLegacy : public IOService {
 OSDeclareAbstractStructors(IOMobileFramebufferLegacy)
 unsigned char originalPrivate[0x19c0-sizeof(IOService)];
public:
 // Width and height as the original slot-251 getter reads them.
 void installBootDimensions(uint32_t width,uint32_t height) {
  *reinterpret_cast<uint32_t *>(reinterpret_cast<unsigned char *>(this)+6088)=width;
  *reinterpret_cast<uint32_t *>(reinterpret_cast<unsigned char *>(this)+6092)=height;
 }
 const OriginalLegacySwapRequest *pendingSwapRequest() const {
  const OriginalLegacySwapRequest *request=nullptr;
  memcpy(&request,reinterpret_cast<const unsigned char *>(this)+5744,sizeof(request));return request;
 }
 // Tail queue: head +5744, tail pointer +5752, each request's next at +3072 and previous-link at +3080; the current swap
 // is +5736. Same operation as the 21H461 helper (sheng build-gop-legacy-display.py), at the 22H384 offsets.
 bool activateOnlyPendingSwap(const OriginalLegacySwapRequest *request) {
  auto self=reinterpret_cast<unsigned char *>(this);
  auto bytes=reinterpret_cast<const unsigned char *>(request);
  const void *current=nullptr,*head=nullptr,*tail=nullptr,*next=nullptr,*previous=nullptr;
  memcpy(&current,self+5736,8);memcpy(&head,self+5744,8);memcpy(&tail,self+5752,8);
  if(!request || current || head!=request)return false;
  memcpy(&next,bytes+3072,8);memcpy(&previous,bytes+3080,8);
  if(previous!=self+5744)return false;
  if(next) {
   const void *link=self+5744;
   memcpy(const_cast<unsigned char *>(reinterpret_cast<const unsigned char *>(next))+3080,&link,8);
  } else if(tail!=bytes+3072)return false;
  memcpy(self+5736,&request,8);
  if(next) {memcpy(self+5744,&next,8);}
  else {const void *empty=nullptr,*emptyTail=self+5744;memcpy(self+5744,&empty,8);memcpy(self+5752,&emptyTail,8);}
  return true;
 }
 void free() override;
 bool init(OSDictionary *properties=nullptr) override;
 IOReturn setProperties(OSObject *) override;
 void systemWillShutdown(IOOptionBits) override;
 IOService *probe(IOService *,SInt32 *) override;
 bool start(IOService *) override;
 void stop(IOService *) override;
 IOWorkLoop *getWorkLoop() const override;
 IOReturn newUserClient(task_t,void *,UInt32,IOUserClient **) override;
 IOReturn setPowerState(unsigned long,IOService *) override;
'''
named = {184: ' virtual bool isMainDisplay();\n', 188: ' virtual IOReturn getDotPitch(uint32_t *);\n',
         214: ' virtual IOReturn supportedFrameInfo(uint32_t,uint32_t *,char *,uint32_t *)=0;\n',
         251: ' virtual void getDisplayDimensions(uint32_t *,uint32_t *);\n', 296: ' virtual bool startHardware();\n',
         298: ' virtual void kickSwapQueue();\n', 303: ' virtual void completeCurrentSwap();\n',
         304: ' virtual bool validateSwap(const OriginalLegacySwapRequest *);\n',
         309: ' virtual bool getRefreshAttributes(uint64_t *,bool);\n',
         355: ' virtual uint32_t dpLinkState()=0;\n',
         347: ' virtual IOReturn collectCompletionReports(uint32_t,void *,uint32_t *,uint32_t)=0;\n'}
for i in range(168, SLOTS):
    if i in named:
        header += named[i]
    elif i in PURE:
        header += f' virtual __attribute__((noreturn)) void opaque{i}()=0;\n'
    else:
        header += f' virtual __attribute__((deprecated("Unclassified ABI: never call from source"))) void opaque{i}();\n'
header += '};\nstatic_assert(sizeof(IOMobileFramebufferLegacy)==0x19c0,"Actual original instance extent");\n'
(out / 'OriginalLegacyFramebufferABI.h').write_text(header)

# 2. The display source with the 22H384 offsets and without the CPU copy fallback. Every edit must apply exactly.
source = (gop / 'NativeLegacyDisplay.cpp').read_text()
edits = [('reinterpret_cast<const unsigned char *>(this)+5592', 'reinterpret_cast<const unsigned char *>(this)+5856', 1),
         ('reinterpret_cast<void **>(this))[354]', 'reinterpret_cast<void **>(this))[364]', 1),
         ('+2624,', '+2632,', 3)]
for old, new, count in edits:
    if source.count(old) != count:
        fail(f'{old!r} occurs {source.count(old)} times, expected {count}')
    source = source.replace(old, new)
leaves = {211: 212, 245: 247, 246: 248, 306: 314, 307: 315, 338: 348, 345: 355}
for old, new in leaves.items():
    if source.count(f'    LEAF({old})\n') != 1:
        fail(f'LEAF({old}) not found once')
    source = source.replace(f'    LEAF({old})\n', f'    LEAF({new})\n')
# Slot 355 (abstract; 21H461 345) only feeds the DPLink field of swap_wait_gated's timeout log (run 31 panic): no
# DisplayPort link on the internal GOP panel.
if source.count('    LEAF(355)\n') != 1:
    fail('LEAF(355) not found once')
source = source.replace('    LEAF(355)\n', '    uint32_t dpLinkState() override {return 0;}\n')
cpu_copy = '        IOMemoryMap *source=memory->map(kIOMapAnywhere|kIOMapReadOnly);\n'
if source.count(cpu_copy) != 1:
    fail('CPU copy fallback not found once')
source = source.replace(cpu_copy, '        // blueline: no CPU copy. A frame the GPU hand-off refused stays pending until the GPU takes it.\n'
                        '        native_legacy_gpu_fallback_observed(-1);native_legacy_transfer_observed(kIOReturnNotReady,request,0);return;\n'
                        + cpu_copy)
if re.search(r'\+(5592|5472|5480|5488|5808|5812|2624|2960|2968)\b', re.sub(r'//[^\n]*', '', source)):
    fail('a 21H461 offset is left in NativeLegacyDisplay.cpp')
unit = out / 'NativeLegacyDisplay.cpp'
unit.write_text(source)

# 3. Compile with the XNU C++ recipe.
recipe = json.loads((tree / 'build/xnu/ios-obj/DEVELOPMENT_ARM64_BCM2837/iokit/DEVELOPMENT/IOPlatformExpert.cpo.json')
                    .read_text().strip().rstrip(','))


def compile_cpp(src, obj, extra=()):
    cmd, i, args = [], 0, recipe['arguments']
    while i < len(args):
        v = args[i]
        if v == recipe['file']:
            cmd.append(str(src))
        elif v == '-o':
            cmd += ['-o', str(obj)]
            i += 1
        elif v in ('-MF', '-MJ'):
            i += 1
        elif v == '-Xclang' and args[i + 1].startswith('-W'):
            i += 1
        elif not v.startswith('-W') and v not in ('-MD', '-MP'):
            cmd.append(v)
        i += 1
    cmd += ['-Wall', '-Wextra', '-Werror', '-Wno-unused-parameter', '-Wno-unnecessary-virtual-specifier', '-Wno-c99-designator',
            '-Wno-reorder-init-list', '-Wno-deprecated-enum-enum-conversion', '-Wno-deprecated-declarations',
            '-Wno-overloaded-virtual', '-I', str(out), '-I', str(gop), '-I', str(tree / '.cache/xnu-work/osfmk'), *extra]
    run = subprocess.run(cmd, cwd=recipe['directory'], capture_output=True, text=True)
    (out / (obj.stem + '.log')).write_text(run.stdout + run.stderr)
    if run.returncode:
        fail(f'{src}:\n{run.stderr[-5000:]}')
    return obj


display_obj = compile_cpp(unit, out / 'NativeLegacyDisplay.o')
presenter_obj = compile_cpp(gop / 'NativeGOPPresenter.cpp', out / 'NativeGOPPresenter.o')
probe_obj = compile_cpp(here / 'BluelineDisplayProbe.cpp', out / 'BluelineDisplayProbe.o')

# 4. The compiled vtable must have exactly 368 entries; owned entries are exactly the qualified set.
raw = display_obj.read_bytes()
image = macho(raw)
st = next(q for c, q, _ in image['commands'] if c == 2)
sy, count, strings, _ = struct.unpack_from('<4I', raw, st + 8)
symbols = []
for i in range(count):
    ix, kind, section, _, va = struct.unpack_from('<IBBHQ', raw, sy + i * 16)
    symbols.append((raw[strings + ix:raw.index(b'\0', strings + ix)].decode(), va, kind))
vtable = next(va for name, va, _ in symbols if name == '__ZTV19NativeLegacyDisplay')
relocations = {}
for segment in image['segments']:
    for sec in segment['sections']:
        if sec['va'] <= vtable < sec['va'] + sec['size']:
            ro, rc = struct.unpack_from('<2I', raw, sec['command_offset'] + 56)
            for i in range(rc):
                offset, bits = struct.unpack_from('<2I', raw, ro + i * 8)
                if bits >> 27 & 1 and bits >> 28 == 0 and bits >> 25 & 3 == 3:
                    relocations[sec['va'] + offset] = symbols[bits & 0xffffff][0]
compiled = [relocations.get(vtable + 16 + i * 8) for i in range(SLOTS)]
if not all(compiled) or vtable + 16 + SLOTS * 8 in relocations:
    fail('compiled vtable is not exactly 368 entries')
owned = [i for i, n in enumerate(compiled) if n.startswith(('__ZN19NativeLegacyDisplay', '__ZNK19NativeLegacyDisplay'))]
if owned != sorted(OWNED_BASE + PURE):
    fail(f'owned slots {owned}')

# 5. Bindings. Original vtable entries of the 22H384 kernelcache, shifted, must equal the built kernel's entries.
KC_VTABLE = 0xfffffff006d4fcf0   # __ZTV25IOMobileFramebufferLegacy (constructor vptr 0xfffffff006d4fd00 - 16)
kc_entries = struct.unpack(f'<{SLOTS}Q', kc.read(KC_VTABLE + 16, SLOTS * 8))
our_entries = struct.unpack(f'<{SLOTS}Q', ours.read(KC_VTABLE - SHIFT + 16, SLOTS * 8))
names = {n: v for v, group in exports(ours.raw, ours.im).items() for n in group}
pure_virtual = names.get('___cxa_pure_virtual')
for i in range(168, SLOTS):
    if (i in PURE) != (our_entries[i] == pure_virtual):
        fail(f'abstract slot set differs at {i}')
bindings = {'__ZN25IOMobileFramebufferLegacyC2EPK11OSMetaClass': 0xfffffff005c1c034,
            '__ZN25IOMobileFramebufferLegacyD2Ev': 0xfffffff005c1c058,
            '__ZN25IOMobileFramebufferLegacy10gMetaClassE': 0xfffffff007bbe580,
            '__ZTV25IOMobileFramebufferLegacy': KC_VTABLE,
            '_native_legacy_vsync_notify': 0xfffffff005c23b18,
            '_native_legacy_set_refresh_properties': 0xfffffff005c26ef8}
getters = [('descriptor', 0xfffffff005a9ac60, 48, True), ('format', 0xfffffff005a9ad24, 128, False),
           ('width', 0xfffffff005a9ad34, 88, True), ('height', 0xfffffff005a9ad3c, 96, True),
           ('stride', 0xfffffff005a9ad4c, 104, True), ('planes', 0xfffffff005a9ad6c, 152, False),
           ('allocation', 0xfffffff005a9ad74, 144, True)]
for name, address, field, wide in getters:
    expected = struct.pack('<2I', (0xf9400000 if wide else 0xb9400000) | ((field // (8 if wide else 4)) << 10), 0xd65f03c0)
    if kc.read(address, 8) != expected:
        fail('IOSurface getter ' + name)
    bindings['_native_legacy_surface_' + name] = address
for i, name in enumerate(compiled):
    if '25IOMobileFramebufferLegacy' in name:
        if i in PURE:
            fail(f'original abstract slot {i} inherited')
        bindings[name] = kc_entries[i]
    elif i < 168 and not name.startswith(('__ZN19NativeLegacyDisplay', '__ZNK19NativeLegacyDisplay')):
        if names.get(name) != our_entries[i]:
            fail(f'inherited kernel base symbol at slot {i}')
undefined = {n for n, _, k in symbols if k == 1 and 'IOMobileFramebufferLegacy' in n}
missing = undefined - set(bindings)
if missing:
    fail(f'unbound original imports {sorted(missing)}')
# Every bound code/data address must hold the same bytes in the kernelcache and, shifted, in our kernel.
for name, address in bindings.items():
    if kc.read(address, 16) != ours.read(address - SHIFT, 16):
        fail(f'{name}: kernelcache and built kernel differ at the shifted address')
# Structural checks of the named family functions (docs/DISPLAY-22H384.md).
if kc.read(0xfffffff005c27ae4, 4) != struct.pack('<I', 0x52800003 | (SIZE << 5)):
    fail('IOMobileFramebufferLegacy metaclass size is not 0x19c0')
getter = kc_entries[251]
code = kc.read(getter, 0x80)
for field in (6088, 6092):
    if not any((w & 0xffc00000) == 0xb9400000 and ((w >> 10) & 0xfff) * 4 == field for w in struct.unpack('<32I', code)):
        fail(f'slot 251 does not read field {field}')
asm = out / 'original-bindings.S'
asm.write_text(''.join(f'.globl {n}\n.set {n}, {v - SHIFT:#x}\n' for n, v in sorted(bindings.items())
                       if n in undefined or not n.startswith('__ZN25')))
sdk = subprocess.check_output(['xcrun', '--sdk', 'iphoneos', '--show-sdk-path'], text=True).strip()
subprocess.run(['xcrun', 'clang', '-target', 'arm64-apple-ios17.0', '-isysroot', sdk, '-c', str(asm), '-o',
                str(out / 'original-bindings.o')], check=True)


# 6. Stage both class initializers out of __mod_init_func (they run from native_legacy_display_probe).
def stage_late(obj, initializer):
    data = bytearray(obj.read_bytes())
    ncmds = struct.unpack_from('<I', data, 16)[0]
    at, renamed, external = 32, 0, False
    for _ in range(ncmds):
        cmd_id, size = struct.unpack_from('<2I', data, at)
        if cmd_id == 0x19:
            for s in range(struct.unpack_from('<I', data, at + 64)[0]):
                sect = at + 72 + s * 80
                if data[sect:sect + 16].rstrip(b'\0') == b'__mod_init_func':
                    data[sect:sect + 16] = b'__blueline_init\0'
                    struct.pack_into('<I', data, sect + 64, struct.unpack_from('<I', data, sect + 64)[0] & ~0xff)
                    renamed += 1
        if cmd_id == 2:
            symoff, nsyms, stroff, _ = struct.unpack_from('<4I', data, at + 8)
            for k in range(nsyms):
                strx, ntype = struct.unpack_from('<IB', data, symoff + k * 16)
                if bytes(data[stroff + strx:data.index(b'\0', stroff + strx)]) == initializer.encode():
                    external = bool(ntype & 1)
        at += size
    if renamed != 1 or not external:
        fail(f'{obj.name}: initializer staging (renamed {renamed}, external {external})')
    late = obj.with_suffix('.late.o')
    late.write_bytes(bytes(data))
    return late


# The initializers are local symbols: recompile each class through a wrapper unit that makes it global, as
# build-blueline-accelerator.py does, keeping the source file name so the symbol name is unchanged.
def wrapped(src, name):
    wrap_dir = out / ('wrap-' + Path(name).stem)
    wrap_dir.mkdir(exist_ok=True)
    wrapper = wrap_dir / name
    wrapper.write_text(f'#include "{src}"\n__asm__(".globl \\"__GLOBAL__sub_I_{name}\\"");\n')
    return compile_cpp(wrapper, out / (Path(name).stem + '.o'))


display_obj = wrapped(unit, 'NativeLegacyDisplay.cpp')
presenter_obj = wrapped(gop / 'NativeGOPPresenter.cpp', 'NativeGOPPresenter.cpp')
display_late = stage_late(display_obj, '__GLOBAL__sub_I_NativeLegacyDisplay.cpp')
presenter_late = stage_late(presenter_obj, '__GLOBAL__sub_I_NativeGOPPresenter.cpp')
archive = out / 'libNativeLegacyDisplay.late.a'
archive.unlink(missing_ok=True)
subprocess.run(['xcrun', 'ar', 'rcs', str(archive), str(display_late), str(presenter_late), str(probe_obj),
                str(out / 'original-bindings.o')], check=True)
sha = lambda path: hashlib.sha256(Path(path).read_bytes()).hexdigest()
(out / 'build-report.json').write_text(json.dumps(dict(
    source_sha256={str(s): sha(s) for s in (gop / 'NativeLegacyDisplay.cpp', gop / 'NativeGOPPresenter.cpp', here / 'BluelineDisplayProbe.cpp')},
    generated_abi_sha256=sha(out / 'OriginalLegacyFramebufferABI.h'), kernel=str(a.kernel), kernel_sha256=sha(a.kernel),
    archive_sha256=sha(archive), bindings={n: hex(v - SHIFT) for n, v in bindings.items()}, owned_entries=owned,
    cpu_copy_removed=True, display_presented=False), indent=2) + '\n')
print(f'PASS: NativeLegacyDisplay for 22H384 ({SLOTS} slots, {len(bindings)} bindings checked), CPU copy removed: {archive}')
